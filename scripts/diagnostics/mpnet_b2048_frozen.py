SDK = "0.12.1.dev163+g0c6d4a5e.prod"
PRODUCT = "e5acc2960ec48eb3bcf122ad53428ff878a775f2"
CHECKPOINT = "sentence-transformers/all-mpnet-base-v2"
REVISION = "e8c3b32edf5434bc2275fc9bab85f82640a19130"
COMPILED_SHA256 = "d8ba3ac7d79748e10bc90f09d558973febd9b4e2581d1fcc509acbc4bb6b8460"
FILES = {"config.json", "rbln_config.json", "tokenizer.json", "tokenizer_config.json", "compiled_model.rbln"}
CASE = "TestMPNetModelNativeMaxBatch2048Frozen"
TEXTS = [
    "This is an example sentence.",
    "Each sentence is converted into an embedding.",
    "A long document discusses processors and machine learning. " * 80,
    "",
]


def verify_files(directory):
    import hashlib

    manifest = json.loads((directory / "manifest.json").read_text())
    actual = {str(path.relative_to(directory)) for path in directory.rglob("*") if path.is_file()}
    if set(manifest["files"]) != FILES or actual != FILES | {"manifest.json"}:
        raise ValueError("Frozen directory must contain exactly the five manifested model files")
    for name, receipt in manifest["files"].items():
        path = directory / name
        if path.is_symlink() or not path.resolve().is_relative_to(directory.resolve()):
            raise ValueError("Frozen model files must be ordinary files within the artifact directory")
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
                digest.update(block)
        if path.stat().st_size != receipt["bytes"] or digest.hexdigest() != receipt["sha256"]:
            raise ValueError(f"Checksum/size mismatch: {name}")
    return manifest


def verify_artifacts(directory, inspect_model=None):
    manifest = verify_files(directory)
    expected = {
        "compiler": SDK,
        "checkpoint": CHECKPOINT,
        "revision": REVISION,
        "npu": "RBLN-CR13",
        "batch_size": 2048,
        "max_seq_len": 512,
        "reviewed_product_head": PRODUCT,
    }
    if any(manifest.get(key) != value for key, value in expected.items()):
        raise ValueError("Frozen artifact interface/source review does not match the required model")
    if manifest["files"]["compiled_model.rbln"]["sha256"] != COMPILED_SHA256:
        raise ValueError("Compiled artifact differs from the reviewed frozen binary")
    config = json.loads((directory / "rbln_config.json").read_text())
    cfg = config["_compile_cfgs"]
    inputs = [["input_ids", [2048, 512], "int64"], ["attention_mask", [2048, 512], "int64"]]
    if config["batch_size"] != 2048 or config["max_seq_len"] != 512:
        raise ValueError("Saved model is not native B2048/512")
    if len(cfg) != 1 or cfg[0]["compiled_model_name"] != "compiled_model" or cfg[0]["input_info"] != inputs:
        raise ValueError("Wrong saved native MPNet input interface")
    if cfg[0]["npu"] != "RBLN-CR13" or cfg[0]["num_devices"] != 1:
        raise ValueError("Frozen model must target one CR13")
    native = json.loads((directory / "config.json").read_text())
    if (
        native["model_type"],
        native["num_hidden_layers"],
        native["hidden_size"],
        native["max_position_embeddings"],
    ) != ("mpnet", 12, 768, 514):
        raise ValueError("Wrong full MPNet model configuration")
    if inspect_model is None:
        import rebel

        inspect_model = rebel.RBLNCompiledModel.inspect
    metadata = inspect_model(directory / "compiled_model.rbln")
    profiles = [[row["name"], row["shape"], row["dtype"]] for row in metadata["inputs"]]
    if profiles != inputs or metadata["npu"] != "RBLN-CR13" or metadata["num_devices"] != 1:
        raise ValueError("Compiled metadata does not match saved native inputs/target")
    if metadata["compiler_version"] != SDK.removesuffix(".prod"):
        raise ValueError("Compiled binary was not generated by the pinned SDK163 compiler")
    if [row["shape"] for row in metadata["outputs"]] != [[2048, 512, 768], [2048, 768]]:
        raise ValueError("Wrong native full-model output metadata")
    if sum(metadata["alloc_per_node"]) != manifest["device_alloc_bytes"]:
        raise ValueError("Compiled allocation metadata differs from the manifest budget")
    return {
        "manifest": manifest,
        "compiled_metadata": {
            key: metadata[key]
            for key in ("npu", "num_devices", "inputs", "outputs", "uuid", "compiler_version", "alloc_per_node")
        },
        "compile_checkout_head_captured": False,
        "provenance_note": "Original invocation did not capture checkout HEAD; reviewed_product_head is a later source review.",
    }


class Recorder:
    def __init__(self, directory):
        self.directory = directory
        self.current = None
        self.expected_methods = set()
        self.collected = 0
        self.failed = []
        self.skipped = []
        self.runtime_calls = 0

    def event(self, **row):
        with (self.directory / "events.jsonl").open("a") as stream:
            stream.write(json.dumps({"test": self.current, "time_ns": time.time_ns(), **row}) + "\n")

    def pytest_collection_modifyitems(self, items):
        self.collected = len(items)
        if {item.cls.__name__ for item in items} != {CASE} or {
            item.originalname for item in items
        } != self.expected_methods:
            raise ValueError("Must run every inherited original method plus the strict reload/tuple test")
        if self.collected != len(self.expected_methods):
            raise ValueError("Duplicate or missing original test methods")

    def pytest_runtest_logstart(self, nodeid, location):
        self.current = nodeid
        self.event(phase="test_start")

    def pytest_runtest_logreport(self, report):
        if report.failed:
            self.failed.append(f"{report.nodeid}:{report.when}")
        if report.skipped:
            self.skipped.append(f"{report.nodeid}:{report.when}")
        self.event(phase="test_report", when=report.when, outcome=report.outcome)


def disk_receipts():
    paths = {Path.cwd().resolve(), Path(tempfile.gettempdir()).resolve()}
    receipts = {str(path): shutil.disk_usage(path).free for path in paths}
    if min(receipts.values()) < 64 * 1024**3:
        raise ValueError("At least 64 GiB free is required in both working and temporary storage for copies/save-load")
    return receipts


def frozen_setup(source, recorder):
    def setup(cls):
        destination = Path(cls.get_rbln_local_dir()).resolve()
        if destination == source.resolve() or source.resolve() in destination.parents:
            raise ValueError("Tests must copy into independent local storage")
        recorder.event(phase="local_copy_start")
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(source, destination)
        verify_files(destination)
        recorder.event(phase="local_copy_verified", path=str(destination))
        cls.model = cls.RBLN_CLASS.from_pretrained(destination, rbln_device=0)

    return classmethod(setup)


def repeat_reload_tuple(self):
    import torch
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(self.HF_MODEL_ID, **self.HF_CONFIG_KWARGS)
    inputs = tokenizer(
        [TEXTS[index % len(TEXTS)] for index in range(self.BATCH_SIZE)],
        padding="max_length",
        max_length=512,
        truncation=True,
        return_tensors="pt",
    )
    assert list(inputs["input_ids"].shape) == [self.BATCH_SIZE, 512]
    with torch.no_grad():
        baseline = tuple(value.clone() for value in self.model(**inputs, return_dict=True).to_tuple())
        for return_dict in (True, False):
            output = self.model(**inputs, return_dict=return_dict)
            values = output.to_tuple() if return_dict else output
            for actual, expected in zip(values, baseline, strict=True):
                torch.testing.assert_close(actual, expected, rtol=0, atol=0)
            del output, values
        del type(self).model
        gc.collect()
        type(self).model = self.RBLN_AUTO_CLASS.from_pretrained(self.get_rbln_local_dir(), rbln_device=self.DEVICE)
        for actual, expected in zip(self.model(**inputs, return_dict=False), baseline, strict=True):
            torch.testing.assert_close(actual, expected, rtol=0, atol=0)
    print(
        "MPNET_STATE " + json.dumps({"test_class": type(self).__name__, "repeat_reload_tuple": "passed"}), flush=True
    )


def make_case(parent, source, recorder):
    import torch

    if getattr(parent, "__unittest_skip__", False):
        raise ValueError("CR13 parent was imported with a skip flag; start a fresh CR13 diagnostic process")
    original_methods = set(unittest.defaultTestLoader.getTestCaseNames(parent))
    if len(original_methods) != 9:
        raise ValueError("Expected the nine original MPNet methods")
    recorder.expected_methods = original_methods | {"test_repeat_reload_tuple"}
    return type(
        CASE,
        (parent,),
        {
            "__module__": parent.__module__,
            "BATCH_SIZE": 2048,
            "RBLN_CLASS_KWARGS": {**parent.RBLN_CLASS_KWARGS, "rbln_batch_size": 2048},
            "GENERATION_KWARGS": {
                "input_ids": torch.full((2048, 512), 4, dtype=torch.int64),
                "attention_mask": torch.ones((2048, 512), dtype=torch.int64),
            },
            "setUpClass": frozen_setup(source, recorder),
            "test_repeat_reload_tuple": repeat_reload_tuple,
        },
    )


def run_tests(source, recorder, collect_only=False):
    import pytest

    with patch.dict(
        os.environ, {"RBLN_TEST_NPU": "RBLN-CR13", "OPTIMUM_RBLN_TEST_LEVEL": "full", "PYTEST_ADDOPTS": ""}
    ):
        from tests import test_transformers

        case = make_case(test_transformers.TestMPNetModelNativeMaxBatch1024, source, recorder)
        model_class = case.RBLN_CLASS
        original_forward = model_class.forward

        def forward(self, *args, **kwargs):
            recorder.runtime_calls += 1
            call = recorder.runtime_calls
            recorder.event(phase="runtime_call_start", call=call)
            start = time.perf_counter()
            error = None
            try:
                return original_forward(self, *args, **kwargs)
            except BaseException as exc:
                error = repr(exc)
                raise
            finally:
                recorder.event(phase="runtime_call_end", call=call, seconds=time.perf_counter() - start, error=error)

        with patch.object(test_transformers, CASE, case, create=True), patch.object(model_class, "forward", forward):
            args = [
                f"tests/test_transformers.py::{CASE}",
                "-vv",
                "-s",
                "--durations=0",
                "-o",
                "addopts=",
                f"--junitxml={recorder.directory / 'junit.xml'}",
            ]
            if collect_only:
                args.append("--collect-only")
            return int(pytest.main(args, plugins=[recorder]))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifacts", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("debug-mpnet-b2048-frozen"))
    parser.add_argument("--verify-only", action="store_true", help="SDK/hash/metadata checks; never create a runtime")
    parser.add_argument(
        "--collect-only", action="store_true", help="Collect original diagnostic methods without runtimes"
    )
    args = parser.parse_args(argv)
    args.output.mkdir(parents=True, exist_ok=True)
    for name in ("junit.xml", "events.jsonl", "result.json"):
        (args.output / name).unlink(missing_ok=True)
    recorder = Recorder(args.output.resolve())
    result = {
        "accepted": False,
        "runtime_executed": False,
        "phase": "preflight",
        "full_device_acceptance": False,
        "placement": "SDK163 default mixed CPU embeddings / NPU encoder",
        "full_device_acceptance_blocker": "Frozen SDK163 executes learned word and position embedding lookups on CPU",
    }
    code = 1
    try:
        if os.environ.get("REUSE_ARTIFACTS_PATH") or os.environ.get("SAVE_ARTIFACTS_PATH"):
            raise ValueError("Artifact compatibility environment skips original numerical acceptance")
        if args.collect_only:
            result["phase"] = "collection"
            code = run_tests(args.artifacts.resolve(), recorder, collect_only=True)
            result["collected"] = recorder.collected
        else:
            result["sdk"] = importlib.metadata.version("rebel-compiler")
            if result["sdk"] != SDK:
                raise ValueError(f"Expected SDK163 {SDK}, got {result['sdk']}")
            result["phase"] = "verify"
            result["verification"] = verify_artifacts(args.artifacts.resolve())
            if args.verify_only:
                code = 0
                result["phase"] = "verified_only"
            else:
                result["storage_free_bytes"] = disk_receipts()
                result.update(phase="tests", runtime_requested=True)
                code = run_tests(args.artifacts.resolve(), recorder)
                result.update(
                    collected=recorder.collected,
                    failed=recorder.failed,
                    skipped=recorder.skipped,
                    runtime_executed=recorder.runtime_calls > 0,
                    runtime_call_attempts=recorder.runtime_calls,
                )
                if recorder.failed or recorder.skipped or recorder.collected != 10:
                    code = 1
                result.update(phase="finished", numerical_tests_passed=code == 0)
    except BaseException:
        result["error"] = traceback.format_exc()
        print(result["error"], flush=True)
    finally:
        result["exit_code"] = code
        (args.output / "result.json").write_text(json.dumps(result, indent=2) + "\n")
        if not (args.output / "junit.xml").exists():
            suite = ET.Element("testsuite", name="mpnet_frozen_preflight", tests="1", failures=str(int(code != 0)))
            case = ET.SubElement(suite, "testcase", name=result["phase"])
            if code:
                ET.SubElement(case, "failure").text = result.get("error", "Preflight failed")
            ET.ElementTree(suite).write(args.output / "junit.xml", encoding="unicode")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
